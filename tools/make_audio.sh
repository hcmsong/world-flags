OUT="$(cd "$(dirname "$0")/.." && pwd)/audio"
mkdir -p "$OUT"

say_m4a() {
  local text="$1"
  local base="$2"
  local tmp="$OUT/${base}.aiff"
  say -v "$VOICE" -o "$tmp" "$text"
  afconvert -f m4af -d aac -b 64000 "$tmp" "$OUT/${base}.m4a"
  rm -f "$tmp"
  echo "  $base.m4a"
}

